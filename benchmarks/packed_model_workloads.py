"""Before/current retained models: text/SST placement and mixed styled values."""

import argparse
import hashlib
import json
import statistics
import tempfile
from pathlib import Path

from editable_engines import BINARY, HERE, measure


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--before", type=Path, required=True)
    parser.add_argument("--before-core", default="4279dcb")
    parser.add_argument("--rows", nargs="+", type=int, default=[10000, 100000])
    parser.add_argument("--runs", type=int, default=3)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    report = {
        "method": f"One warmup and {args.runs} rotating serial release samples. Complete retained model plus every-value/coordinate verification inside each native worker; import/build/generation excluded. Identical worker source/lockfile/toolchain, prior core {args.before_core} versus candidate; hashes identify binaries. Calamine returns retained noneditable text ranges; CrabXL retains editable models plus source catalogs.",
        "binary_sha256": {
            label: hashlib.sha256(binary.read_bytes()).hexdigest()
            for label, binary in (("before", args.before), ("after", BINARY))
        },
        "resource_settings": "CrabXL 1 GiB joint/model allowances, 256 MiB SST allowance, 1 MiB decoded disk cache; explicit RAM/disk policy. These are managed allowances, not an RSS limit. Calamine uses its defaults.",
        "cases": [],
    }
    for rows in args.rows:
        for kind, unique in (
            ("repeated-text", 128),
            ("unique-text", rows * 10),
            ("styled", 0),
        ):
            source = HERE / "data" / f"xml-scope-{kind}-{rows}.xlsx"
            # Reuse the exact fixtures generated by xml_scope_checkpoint before
            # timing; never build or generate concurrently with a measurement.
            mode = "crabxl-text-model" if unique else "crabxl-styled-model"
            variants = [
                (label + ":" + policy, binary, mode, policy)
                for policy in (("memory", "disk") if unique else ("memory",))
                for label, binary in (("before", args.before), ("after", BINARY))
            ]
            if unique:
                variants.append(
                    ("calamine:memory", BINARY, "calamine-text-model", "memory")
                )
            case = {
                "rows": rows,
                "kind": kind,
                "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
                "samples": {},
            }
            with tempfile.TemporaryDirectory(
                prefix="crabxl-packed-model-"
            ) as temporary:
                directory = Path(temporary)
                for repeat in range(args.runs + 1):
                    offset = repeat % len(variants)
                    for label, binary, operation, policy in (
                        variants[offset:] + variants[:offset]
                    ):
                        output, measured = measure(
                            [
                                binary,
                                source,
                                operation,
                                directory / "output.xlsx",
                                unique,
                                policy,
                            ],
                            directory,
                        )
                        assert output["cells"] == rows * 10
                        assert output["checksum"] == rows * 10 * (110 if unique else 1)
                        assert output["sheets"] == 1 and output["output_bytes"] == 0
                        assert not list(directory.iterdir()), list(directory.iterdir())
                        if repeat:
                            case["samples"].setdefault(label, []).append(measured)
                        print(
                            json.dumps(
                                {
                                    "rows": rows,
                                    "kind": kind,
                                    "label": label,
                                    "repeat": repeat,
                                    **measured,
                                }
                            ),
                            flush=True,
                        )
            case["medians"] = {
                label: {
                    key: statistics.median(sample[key] for sample in samples)
                    for key in samples[0]
                }
                for label, samples in case["samples"].items()
            }
            report["cases"].append(case)
            args.output.write_text(json.dumps(report, indent=2) + "\n")


if __name__ == "__main__":
    main()
